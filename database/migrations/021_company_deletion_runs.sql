CREATE TABLE IF NOT EXISTS company_deletion_runs (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id INT UNSIGNED NOT NULL,
    company_name VARCHAR(255) NOT NULL,
    db_identifier VARCHAR(64) NOT NULL,
    actor_user_id INT UNSIGNED NOT NULL,
    actor_role VARCHAR(32) NOT NULL,
    backup_id CHAR(32) NOT NULL,
    backup_manifest_sha256 CHAR(64) NOT NULL,
    database_archive_sha256 CHAR(64) NOT NULL,
    storage_archive_sha256 CHAR(64) NOT NULL,
    restore_receipt_sha256 CHAR(64) NOT NULL,
    backup_created_at DATETIME NOT NULL,
    backup_expires_at DATETIME NOT NULL,
    status VARCHAR(16) NOT NULL,
    stage VARCHAR(32) NOT NULL,
    error_code VARCHAR(64) DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    completed_at TIMESTAMP NULL DEFAULT NULL,
    UNIQUE KEY uq_company_deletion_runs_company (company_id),
    UNIQUE KEY uq_company_deletion_runs_backup (backup_id),
    INDEX idx_company_deletion_runs_status (status, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
