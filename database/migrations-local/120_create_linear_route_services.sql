CREATE TABLE IF NOT EXISTS linear_route_services (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    linear_route_id INT UNSIGNED NOT NULL,
    contractor_id INT UNSIGNED NOT NULL,
    service_name VARCHAR(190) NOT NULL,
    description TEXT NULL,
    sort_order INT UNSIGNED NOT NULL DEFAULT 0,
    created_by_user_id INT UNSIGNED NULL,
    created_by_role VARCHAR(40) NULL,
    updated_by_user_id INT UNSIGNED NULL,
    updated_by_role VARCHAR(40) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    deleted_by_user_id INT UNSIGNED NULL,
    deleted_by_role VARCHAR(40) NULL,
    PRIMARY KEY (id),
    KEY idx_linear_route_services_route (linear_route_id, deleted_at, sort_order, id),
    KEY idx_linear_route_services_contractor (contractor_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS linear_route_service_payments (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    linear_route_service_id INT UNSIGNED NOT NULL,
    amount DECIMAL(15,2) NOT NULL,
    payment_type VARCHAR(100) NULL,
    payment_method VARCHAR(20) NOT NULL DEFAULT 'cashless',
    vat_rate VARCHAR(10) NULL,
    condition_type VARCHAR(100) NOT NULL,
    days_count INT UNSIGNED NULL,
    days_kind VARCHAR(20) NULL,
    specific_due_date DATE NULL,
    condition_comment VARCHAR(500) NULL,
    calculated_due_date DATE NULL,
    paid_amount DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    status VARCHAR(40) NOT NULL DEFAULT 'planned',
    sort_order INT UNSIGNED NOT NULL DEFAULT 0,
    created_by_user_id INT UNSIGNED NULL,
    created_by_role VARCHAR(40) NULL,
    updated_by_user_id INT UNSIGNED NULL,
    updated_by_role VARCHAR(40) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    deleted_by_user_id INT UNSIGNED NULL,
    deleted_by_role VARCHAR(40) NULL,
    PRIMARY KEY (id),
    KEY idx_linear_route_service_payments_service (linear_route_service_id, deleted_at, sort_order, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
