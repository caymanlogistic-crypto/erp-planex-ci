CREATE TABLE IF NOT EXISTS `waste_trips` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `client_id` INT UNSIGNED NOT NULL,
  `route_executor_id` INT UNSIGNED NULL,
  `responsible_user_id` INT UNSIGNED NOT NULL,
  `destination_type` ENUM('utilizer','warehouse') NOT NULL,
  `utilizer_id` BIGINT UNSIGNED NULL,
  `status` ENUM('searching_executor','executor_assigned','in_progress','completed','cancelled') NOT NULL DEFAULT 'searching_executor',
  `planned_start_mode` ENUM('exact','range','unspecified') NOT NULL DEFAULT 'unspecified',
  `planned_start_date` DATE NULL,
  `planned_start_date_from` DATE NULL,
  `planned_start_date_to` DATE NULL,
  `actual_start_date` DATE NULL,
  `actual_end_date` DATE NULL,
  `comment` VARCHAR(500) NULL,
  `cancellation_reason` VARCHAR(500) NULL,
  `cancelled_at` DATETIME NULL,
  `cancelled_by_user_id` INT UNSIGNED NULL,
  `cancelled_by_role` VARCHAR(20) NULL,
  `source_system` VARCHAR(50) NULL,
  `legacy_flight_id` BIGINT UNSIGNED NULL,
  `lock_version` INT UNSIGNED NOT NULL DEFAULT 1,
  `created_by_user_id` INT UNSIGNED NULL,
  `created_by_role` VARCHAR(20) NULL,
  `updated_by_user_id` INT UNSIGNED NULL,
  `updated_by_role` VARCHAR(20) NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_waste_trip_legacy_identity` (`source_system`,`legacy_flight_id`),
  KEY `idx_waste_trips_status` (`status`,`id`),
  KEY `idx_waste_trips_client` (`client_id`,`id`),
  KEY `idx_waste_trips_executor` (`route_executor_id`,`id`),
  KEY `idx_waste_trips_responsible` (`responsible_user_id`,`id`),
  KEY `idx_waste_trips_utilizer` (`utilizer_id`,`id`),
  KEY `idx_waste_trips_dates` (`planned_start_date`,`planned_start_date_from`,`planned_start_date_to`),
  CONSTRAINT `fk_waste_trips_client` FOREIGN KEY (`client_id`) REFERENCES `clients` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_waste_trips_executor` FOREIGN KEY (`route_executor_id`) REFERENCES `crews` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_waste_trips_responsible` FOREIGN KEY (`responsible_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_waste_trips_utilizer` FOREIGN KEY (`utilizer_id`) REFERENCES `feo_utilizers` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `waste_trip_requests` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `waste_trip_id` BIGINT UNSIGNED NOT NULL,
  `feo_request_id` BIGINT UNSIGNED NOT NULL,
  `snapshot_mass_kg` DECIMAL(18,3) NOT NULL,
  `position_no` INT UNSIGNED NOT NULL DEFAULT 0,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_waste_trip_request` (`waste_trip_id`,`feo_request_id`),
  KEY `idx_waste_trip_requests_request` (`feo_request_id`,`waste_trip_id`),
  KEY `idx_waste_trip_requests_position` (`waste_trip_id`,`position_no`,`id`),
  CONSTRAINT `fk_waste_trip_requests_trip` FOREIGN KEY (`waste_trip_id`) REFERENCES `waste_trips` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_waste_trip_requests_feo` FOREIGN KEY (`feo_request_id`) REFERENCES `feo_requests` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `waste_trip_legacy_import_audits` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `waste_trip_id` BIGINT UNSIGNED NOT NULL,
  `source_system` VARCHAR(50) NOT NULL,
  `legacy_flight_id` BIGINT UNSIGNED NOT NULL,
  `legacy_payload_json` LONGTEXT NOT NULL,
  `mapping_json` LONGTEXT NOT NULL,
  `snapshot_request_count` INT UNSIGNED NOT NULL,
  `snapshot_total_mass_kg` DECIMAL(18,3) NOT NULL,
  `mass_delta_kg` DECIMAL(18,3) NULL,
  `warnings_json` LONGTEXT NULL,
  `legacy_total_mass_kg` DECIMAL(18,3) NULL,
  `legacy_cost` DECIMAL(18,2) NULL,
  `legacy_payment_terms` VARCHAR(500) NULL,
  `imported_by_user_id` INT UNSIGNED NULL,
  `imported_by_role` VARCHAR(20) NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_waste_trip_legacy_audit_identity` (`source_system`,`legacy_flight_id`),
  UNIQUE KEY `uk_waste_trip_legacy_audit_trip` (`waste_trip_id`),
  CONSTRAINT `fk_waste_trip_legacy_audit_trip` FOREIGN KEY (`waste_trip_id`) REFERENCES `waste_trips` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `waste_trip_audit_log` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `waste_trip_id` BIGINT UNSIGNED NOT NULL,
  `action` ENUM('create','update','composition_correction','cancel','import') NOT NULL,
  `before_json` LONGTEXT NULL,
  `after_json` LONGTEXT NULL,
  `actor_user_id` INT UNSIGNED NULL,
  `actor_role` VARCHAR(20) NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_waste_trip_audit_trip` (`waste_trip_id`,`id`),
  CONSTRAINT `fk_waste_trip_audit_trip` FOREIGN KEY (`waste_trip_id`) REFERENCES `waste_trips` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
