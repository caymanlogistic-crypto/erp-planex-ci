CREATE TABLE IF NOT EXISTS `feo_import_changes` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `import_id` BIGINT UNSIGNED NOT NULL,
  `zayavka_id` VARCHAR(64) NOT NULL,
  `action` ENUM('insert','update') NOT NULL,
  `previous_import_id` BIGINT UNSIGNED NULL,
  `before_json` LONGTEXT NULL,
  `after_json` LONGTEXT NOT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_feo_import_changes_import` (`import_id`,`id`),
  KEY `idx_feo_import_changes_request` (`zayavka_id`),
  CONSTRAINT `fk_feo_import_changes_import` FOREIGN KEY (`import_id`) REFERENCES `feo_imports` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
