CREATE TABLE IF NOT EXISTS `feo_imports` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `filename` VARCHAR(255) NOT NULL,
  `file_hash` CHAR(64) NOT NULL,
  `rows_total` INT UNSIGNED NOT NULL DEFAULT 0,
  `unique_requests` INT UNSIGNED NOT NULL DEFAULT 0,
  `new_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `updated_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `unchanged_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `missing_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `status` ENUM('applied','rolled_back') NOT NULL DEFAULT 'applied',
  `created_by_user_id` INT UNSIGNED NULL,
  `created_by_role` VARCHAR(20) NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `rolled_back_by_user_id` INT UNSIGNED NULL,
  `rolled_back_by_role` VARCHAR(20) NULL,
  `rolled_back_at` DATETIME NULL,
  PRIMARY KEY (`id`),
  KEY `idx_feo_imports_status_id` (`status`,`id`),
  KEY `idx_feo_imports_file_hash` (`file_hash`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

