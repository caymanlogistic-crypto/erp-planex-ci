CREATE TABLE IF NOT EXISTS `logist_contracts` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `trip_id` BIGINT UNSIGNED NOT NULL,
  `business_id` INT UNSIGNED NOT NULL,
  `contract_type` ENUM('lease','sublease') NOT NULL,
  `version_no` INT UNSIGNED NOT NULL,
  `template_id` INT UNSIGNED NOT NULL,
  `template_version_id` BIGINT UNSIGNED NOT NULL,
  `route_executor_id` INT UNSIGNED NOT NULL,
  `snapshot_json` LONGTEXT NOT NULL,
  `pdf_path` VARCHAR(1000) NOT NULL,
  `pdf_name` VARCHAR(255) NOT NULL,
  `pdf_sha256` CHAR(64) NOT NULL,
  `status` ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
  `review_reason` VARCHAR(1000) NULL,
  `reviewed_by_user_id` INT UNSIGNED NULL,
  `reviewed_at` DATETIME NULL,
  `created_by_user_id` INT UNSIGNED NOT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_logist_contract_version` (`trip_id`,`contract_type`,`version_no`),
  KEY `idx_logist_contract_creator` (`created_by_user_id`,`id`),
  KEY `idx_logist_contract_status` (`status`,`id`),
  KEY `idx_logist_contract_trip` (`trip_id`,`id`),
  CONSTRAINT `fk_logist_contract_trip` FOREIGN KEY (`trip_id`) REFERENCES `waste_trips` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_logist_contract_template` FOREIGN KEY (`template_id`) REFERENCES `document_templates` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_logist_contract_template_version` FOREIGN KEY (`template_version_id`) REFERENCES `document_template_versions` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_logist_contract_executor` FOREIGN KEY (`route_executor_id`) REFERENCES `crews` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
