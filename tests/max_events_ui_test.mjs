    assert.equal(previewRequests,1);
    await modal.getByRole('button',{name:'Отмена',exact:true}).click();
    assert.equal(await modal.isVisible(),false);
    assert.equal(await page.locator('[data-max-event-edit="0"]').evaluate(e=>e===document.activeElement),true);
    await page.locator('[data-max-event-edit="1"]').click();
    assert.equal(await modal.locator('[data-max-event-variable] option[value="{{block_id}}"]').count(),0);
    assert.equal(await modal.locator('[data-max-event-variable] option[value="{{quality}}"]').count(),1);
    previewFailure=true;await modal.locator('[data-max-event-preview]').click();
    await modal.getByText('Ошибка шаблона',{exact:true}).waitFor();
    previewFailure=false;await modal.locator('[data-max-event-preview]').click();
    await modal.getByText('Пример <b>без выполнения HTML</b>',{exact:true}).waitFor();
    previewDelay=150;await modal.locator('[data-max-event-preview]').click();
    await template.fill('Другой текст {{quality}}');
