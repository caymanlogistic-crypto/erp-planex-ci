    assert.equal(await modal.locator('[name=is_enabled]').isDisabled(),true);
    assert.equal(await template.isDisabled(),true);
    assert.equal(await modal.locator('[name=message_format]').isDisabled(),true);
    assert.equal(await modal.locator('[name=message_format]').inputValue(),'plain');
    assert.equal(await modal.locator('[data-max-system-required-note]').isVisible(),true);
    assert.equal(await modal.locator('[data-max-event-default]').isVisible(),false);
    assert.equal(await modal.locator('[data-max-insert]').isDisabled(),true);
    assert.ok((await template.inputValue()).includes('{{action_title}}'));
    assert.equal(await page.locator('[data-max-event-row]').first().getByText('Системное',{exact:true}).count(),1);
    await modal.locator('[data-max-event-preview]').click();
